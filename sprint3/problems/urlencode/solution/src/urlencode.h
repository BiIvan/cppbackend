#pragma once

#include <string>
#include <string_view>

/*
 * URL-кодирует строку str по правилам задачи:
 * - пробел заменяется на '+';
 * - зарезервированные символы !#$&'()*+,/:;=?@[]
 *   и байты с кодами < 32 или >= 128 заменяются на %HH;
 * - остальные байты остаются без изменения.
 */
std::string UrlEncode(std::string_view str);
